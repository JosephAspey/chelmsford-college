// Builds src/Prototype.Core/CollegeData/college-data.sql from the college's demo course data
// (Appendix 2 - Demo Course Data.xlsx, exported sheet by sheet to tools/course-data/*.json).
// The tables and columns keep the college's own names, so the site queries the same shape as their live SQL.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'course-data');
const load = name => JSON.parse(fs.readFileSync(path.join(dir, `${name}.json`), 'utf8').replace(/^\uFEFF/, ''));

// Excel stores dates as days since 1899-12-30
const fromOaDate = n => new Date(Date.UTC(1899, 11, 30) + Math.round(n * 86400000));
const isNull = v => v === null || v === undefined || v === 'NULL' || (typeof v === 'string' && v.trim() === '');

const sqlText = v => isNull(v) ? 'NULL' : `N'${String(v).replace(/'/g, "''")}'`;
const sqlInt = v => isNull(v) ? 'NULL' : String(Math.trunc(Number(v)));
const sqlDateTime = v => isNull(v) || typeof v !== 'number' ? 'NULL' : `'${fromOaDate(v).toISOString().slice(0, 19)}'`;
// Start dates are a mix of real dates and free text ("Flexible", "October 2026, January 2027 and April 2027.")
const sqlStartDate = v => isNull(v) ? 'NULL' : typeof v === 'number' ? `N'${fromOaDate(v).toISOString().slice(0, 10)}'` : sqlText(v);

const tables = [
  {
    name: 'course_sections',
    columns: { S_ID: 'int NOT NULL PRIMARY KEY', S_TITLE: 'nvarchar(255)', S_DESCRIPTION: 'nvarchar(max)', S_SEOTITLE: 'nvarchar(255)', S_SEOH1: 'nvarchar(255)', S_SEOH2: 'nvarchar(255)', S_SEODESC: 'nvarchar(max)', S_COLOUR: 'nvarchar(50)', S_ICON: 'nvarchar(255)', S_ORDER: 'int', S_CREATED: 'datetime2', S_CREATEDBY: 'int', S_UPDATED: 'datetime2', S_UPDATEDBY: 'int', S_DELETED: 'datetime2', S_DELETEDBY: 'int', S_PUBLISH: 'int', S_AP: 'int' },
  },
  {
    name: 'course_levels',
    columns: { L_ID: 'int NOT NULL PRIMARY KEY', L_TITLE: 'nvarchar(255)', L_IMAGE: 'nvarchar(255)', L_DISABLED: 'int' },
    // The sheet heads this column "L_I,AGE", a typo for L_IMAGE
    sheetColumns: ['L_ID', 'L_TITLE', 'L_I,AGE', 'L_DISABLED'],
  },
  {
    name: 'courses',
    columns: { C_ID: 'int NOT NULL PRIMARY KEY', C_TITLE: 'nvarchar(500)', C_SECTION: 'int', C_MODE: 'nvarchar(10)', C_APPTYPE: 'nvarchar(50)', C_DURATION: 'nvarchar(100)', C_DAYS: 'nvarchar(255)', C_QUALIFICATION: 'nvarchar(max)', C_ADDITIONALQUALS: 'nvarchar(max)', C_COURSECODE: 'nvarchar(50)', C_SHORTCODE: 'nvarchar(50)', C_LEARNINGAIM: 'nvarchar(50)', C_LEVEL: 'nvarchar(50)', C_STARTDATE: 'nvarchar(255)', C_STUDYOVERVIEW: 'nvarchar(max)', C_EMPLOYABILITY: 'nvarchar(max)', C_ELIGIBILITY: 'nvarchar(max)', C_ELIGIBILITYSPECIFIC: 'nvarchar(max)', C_ASSESSMENT: 'nvarchar(max)', C_FEES: 'nvarchar(max)', C_ADDITIONALFEES: 'nvarchar(max)', C_FUNDING: 'nvarchar(max)', C_CONTACT: 'nvarchar(max)', C_METADESC: 'nvarchar(max)', C_SEOTITLE: 'nvarchar(500)', C_SEOH1: 'nvarchar(500)', C_SEOH2: 'nvarchar(500)', C_APPLYFORMTYPE: 'nvarchar(50)', C_COURSEFORME: 'nvarchar(max)', C_YEAR: 'nvarchar(20)', C_CREATED: 'datetime2', C_CREATEDBY: 'int', C_UPDATED: 'datetime2', C_UPDATEDBY: 'int', C_DELETED: 'datetime2', C_DELETEDBY: 'int', C_PUBLISHED: 'int' },
  },
  { name: 'course_level_link', columns: { CL_ID: 'int NOT NULL PRIMARY KEY', CL_COURSEID: 'int NOT NULL', CL_LEVELID: 'int NOT NULL' } },
  { name: 'course_funding', columns: { F_ID: 'int NOT NULL PRIMARY KEY', F_TITLE: 'nvarchar(255)' } },
  { name: 'course_fund_link', columns: { CF_ID: 'int NOT NULL PRIMARY KEY', CF_COURSEID: 'int NOT NULL', CF_FUNDID: 'int NOT NULL' } },
];

const valueFor = (column, type, v) =>
  column === 'C_STARTDATE' ? sqlStartDate(v)
  : type.startsWith('int') ? sqlInt(v)
  : type.startsWith('datetime') ? sqlDateTime(v)
  : sqlText(v);

const out = ['-- Generated by tools/generate-college-data.js from the college\'s demo course data. Do not edit by hand.', ''];
for (const t of tables) {
  const rows = load(t.name);
  const header = rows[0];
  const names = Object.keys(t.columns);
  const sheetNames = t.sheetColumns ?? names;
  const indexes = sheetNames.map(n => header.indexOf(n));
  if (indexes.some(i => i < 0)) throw new Error(`${t.name}: missing column(s) ${sheetNames.filter((n, i) => indexes[i] < 0)}`);

  out.push(`CREATE TABLE dbo.${t.name} (`, names.map(n => `    ${n} ${t.columns[n]}`).join(',\n'), ');', 'GO');
  const data = rows.slice(1).filter(r => !isNull(r[indexes[0]]));
  for (let i = 0; i < data.length; i += 200) {
    out.push(`INSERT INTO dbo.${t.name} (${names.join(', ')}) VALUES`);
    out.push(data.slice(i, i + 200).map(r => `(${names.map((n, j) => valueFor(n, t.columns[n], r[indexes[j]])).join(', ')})`).join(',\n') + ';');
    out.push('GO');
  }
  console.log(`${t.name}: ${data.length} rows`);
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'Prototype.Core', 'CollegeData', 'college-data.sql'), out.join('\n') + '\n');
